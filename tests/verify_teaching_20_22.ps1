param(
    [Parameter(Mandatory=$true)][ValidateSet(20,21,22)][int]$Lesson,
    [string]$InputCsv,
    [string]$Compiler = $env:SMC_CXX
)
$ErrorActionPreference = 'Stop'
$smcRepo = Split-Path -Parent $PSScriptRoot
$smcNames = @{20='第20讲_初始化失败与多个实例';21='第21讲_MATLAB与C++逐次核对';22='第22讲_C++完整实验与重启'}
$smcSourcesByLesson = @{20='position_state_walkthrough';21='position_sequence_runner';22='position_restart_closed_loop'}
$smcLessonBuild = Join-Path $smcRepo ('build/教学/' + $smcNames[$Lesson])
$smcNativeBuild = Join-Path $smcRepo "build/lesson${Lesson}_host"
New-Item -ItemType Directory -Force -Path $smcLessonBuild,$smcNativeBuild | Out-Null
if (!$Compiler) { $Compiler = (Get-Command g++ -ErrorAction Stop).Source }
$smcSource = Join-Path $smcRepo ('examples/' + $smcSourcesByLesson[$Lesson] + '.cpp')
$smcHashPaths = @((Join-Path $smcRepo 'main/ALG_SMC.hpp'),(Join-Path $smcRepo 'main/ALG_SMC.cpp'),$smcSource)
$smcBefore = @(Get-FileHash -LiteralPath $smcHashPaths -Algorithm SHA256 | Select-Object Path,Hash)
$smcReportPath = Join-Path $smcLessonBuild '主机运行报告.json'
@{passed=$false;lesson=$Lesson;hashes=$smcBefore} | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $smcReportPath -Encoding UTF8
$smcExecutable = Join-Path $smcNativeBuild ($smcSourcesByLesson[$Lesson] + '.exe')
$smcCompile = @('-std=c++11','-O2','-Wall','-Wextra','-Wpedantic','-Werror','-fno-fast-math','-ffp-contract=off',
    $smcSource,(Join-Path $smcRepo 'main/ALG_SMC.cpp'),'-o',$smcExecutable)
$smcArguments = @()
$smcSavedPath = $env:PATH
try {
    $env:PATH = (Split-Path -Parent $Compiler) + ';' + $env:PATH
    & $Compiler @smcCompile
    if ($LASTEXITCODE -ne 0) { throw "Lesson $Lesson compile failed" }
    if ($Lesson -eq 21) {
        if (!$InputCsv) { throw 'Lesson 21 requires an input CSV generated by MATLAB' }
        $smcNativeInput = Join-Path $smcNativeBuild 'input.csv'
        Copy-Item -LiteralPath $InputCsv -Destination $smcNativeInput -Force
        $smcArguments = @($smcNativeInput)
    }
    $smcOutput = @(& $smcExecutable @smcArguments)
    if ($LASTEXITCODE -ne 0) { throw "Lesson $Lesson execution failed" }
    $smcExpectedRows = @{20=29;21=4112;22=32000}[$Lesson]
    if ($smcOutput.Count -ne $smcExpectedRows+1) { throw "Unexpected CSV row count: $($smcOutput.Count)" }
    [System.IO.File]::WriteAllLines((Join-Path $smcLessonBuild '真实C++输出.csv'),[string[]]$smcOutput,[System.Text.UTF8Encoding]::new($false))
    $smcAfter = @(Get-FileHash -LiteralPath $smcHashPaths -Algorithm SHA256 | Select-Object Path,Hash)
    for ($smcIndex=0; $smcIndex -lt $smcBefore.Count; $smcIndex++) {
        if ($smcBefore[$smcIndex].Hash -ne $smcAfter[$smcIndex].Hash) { throw 'Source changed during experiment' }
    }
    $smcInputHash = if ($Lesson -eq 21) { (Get-FileHash -LiteralPath $smcNativeInput -Algorithm SHA256).Hash } else { $null }
    @{passed=$true;lesson=$Lesson;compiler=$Compiler;compiler_version=(& $Compiler --version | Select-Object -First 1);
        cxx_standard=11;compile_arguments=$smcCompile;run_arguments=$smcArguments;hashes=$smcAfter;
        input_csv_sha256=$smcInputHash;output_rows=$smcExpectedRows;
        production_sources_modified=$false;production_cpp_executed=$true;reference_sources_modified=$false;
        plant_state_advanced=($Lesson -eq 22);hardware_commands_sent=$false;firmware_linked=$false} |
        ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $smcReportPath -Encoding UTF8
    Write-Output "Lesson ${Lesson}: $smcExpectedRows rows produced by the current production library."
} finally { $env:PATH = $smcSavedPath }
